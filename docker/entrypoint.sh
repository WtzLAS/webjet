#!/bin/sh
# Container entrypoint (docs/docker.md).
#
# For `webjetd run` it prepares the configuration: a mounted
# /etc/webjet/webjetd.toml is used as is, otherwise one is generated from
# WEBJET_* variables. On a fresh data volume it first enrolls the node
# (WEBJET_ENROLL / WEBJET_ENROLL_FILE, with `webjetctl enroll`) or
# initializes the first controller of a new network (WEBJET_GENESIS, with
# `webjetctl init`).
#
# Any other command (`webjetd signer`, webjetctl, sh) runs as given.
set -eu

CONF=${WEBJET_CONFIG:-/run/webjet/webjetd.toml}
DATA=${WEBJET_DATA_DIR:-/var/lib/webjet}
SOCK=${WEBJET_SOCKET:-/run/webjet/control.sock}
MOUNTED=/etc/webjet/webjetd.toml
MARK="# generated by docker-entrypoint from WEBJET_* variables"
ROLE_FILE=/run/webjet-role
NL='
'

log() { echo "docker-entrypoint: $*" >&2; }
die() { log "error: $*"; exit 1; }

# What the healthcheck should test (best effort: /run may be read-only).
role() { echo "$1" > "$ROLE_FILE" 2>/dev/null || true; }

is_true() {
    case "$1" in 1|true|TRUE|True|yes|on) return 0 ;; *) return 1 ;; esac
}

# Values end up in TOML strings: refuse anything that could break out.
safe() {
    case "$2" in
        *\"* | *\\* | *"$NL"*) die "$1 contains a quote, backslash or newline" ;;
    esac
    printf '%s' "$2"
}

# `transport:host:port` → TOML for one [[public]] entry.
public_entry() {
    t=${1%%:*}
    a=${1#*:}
    case "$t" in
        tls|kcp|anytls) ;;
        *) die "WEBJET_PUBLIC entry '$1': transport must be tls, kcp or anytls" ;;
    esac
    case "$a" in
        *:*) ;;
        *) die "WEBJET_PUBLIC entry '$1' needs host:port" ;;
    esac
    printf '[[public]]\naddr = "%s"\ntransport = "%s"\n' "$(safe WEBJET_PUBLIC "$a")" "$t"
}

# `prefix[=interface]` → TOML for one [[gateway.route]]. Without an
# interface, the one the prefix is directly connected to is used.
gateway_entry() {
    prefix=${1%%=*}
    iface=
    case "$1" in *=*) iface=${1#*=} ;; esac
    if [ -z "$iface" ]; then
        route=$(ip -o route get "${prefix%/*}" 2>/dev/null || true)
        case "$route" in
            *" via "*|"") die "no directly connected interface for $prefix; write it as $prefix=<interface>" ;;
        esac
        iface=$(printf '%s\n' "$route" | sed -n 's/.* dev \([^ ]*\).*/\1/p')
        [ -n "$iface" ] || die "could not find the interface for $prefix"
        log "gateway route $prefix via interface $iface"
    fi
    printf '[[gateway.route]]\npublished = "%s"\ninterface = "%s"\n' "$(safe WEBJET_GATEWAY_ROUTES "$prefix")" "$(safe WEBJET_GATEWAY_ROUTES "$iface")"
}

listen_line() { # key value-or-off
    case "$2" in
        ""|off|none|false) ;;
        *) printf '%s = "%s"\n' "$1" "$(safe "listen.$1" "$2")" ;;
    esac
}

generate_config() {
    {
        echo "$MARK"
        printf 'data_dir = "%s"\n' "$(safe WEBJET_DATA_DIR "$DATA")"
        printf 'control_socket = "%s"\n' "$(safe WEBJET_SOCKET "$SOCK")"
        printf 'log = "%s"\n' "$(safe WEBJET_LOG "${WEBJET_LOG:-info}")"
        [ -z "${WEBJET_LOG_FORMAT:-}" ] || printf 'log_format = "%s"\n' "$(safe WEBJET_LOG_FORMAT "$WEBJET_LOG_FORMAT")"
        echo
        echo "[listen]"
        listen_line tls "${WEBJET_LISTEN_TLS-0.0.0.0:443}"
        listen_line kcp "${WEBJET_LISTEN_KCP-0.0.0.0:443}"
        listen_line anytls "${WEBJET_LISTEN_ANYTLS-}"
        echo
        echo "[tun]"
        if is_true "${WEBJET_TUN:-true}"; then echo "enabled = true"; else echo "enabled = false"; fi
        [ -z "${WEBJET_TUN_NAME:-}" ] || printf 'name = "%s"\n' "$(safe WEBJET_TUN_NAME "$WEBJET_TUN_NAME")"
        [ -z "${WEBJET_MTU:-}" ] || printf 'mtu = %d\n' "$WEBJET_MTU"
        echo
        echo "[dns]"
        # systemd-resolved isn't reachable from a container (docs/docker.md).
        if is_true "${WEBJET_CONFIGURE_DNS:-false}"; then echo "configure_system = true"; else echo "configure_system = false"; fi
        echo
        echo "[key]"
        printf 'storage = "%s"\n' "$(safe WEBJET_KEY_STORAGE "${WEBJET_KEY_STORAGE:-auto}")"
        if [ -n "${WEBJET_METRICS_LISTEN:-}" ]; then
            echo
            echo "[metrics]"
            printf 'listen = "%s"\n' "$(safe WEBJET_METRICS_LISTEN "$WEBJET_METRICS_LISTEN")"
        fi
        echo
        echo "[controller]"
        if is_true "${WEBJET_CONTROLLER:-false}"; then echo "enabled = true"; else echo "enabled = false"; fi
        [ -z "${WEBJET_SIGNER_SOCKET:-}" ] || printf 'signer_socket = "%s"\n' "$(safe WEBJET_SIGNER_SOCKET "$WEBJET_SIGNER_SOCKET")"
        [ -z "${WEBJET_HEAD_LIFETIME_HOURS:-}" ] || printf 'head_lifetime_hours = %d\n' "$WEBJET_HEAD_LIFETIME_HOURS"
        if [ -n "${WEBJET_RELAY_CAPACITY_MBPS:-}" ] || [ -n "${WEBJET_RATE_CEILING_MBPS:-}" ]; then
            echo
            echo "[limits]"
            [ -z "${WEBJET_RELAY_CAPACITY_MBPS:-}" ] || printf 'relay_capacity_mbps = %d\n' "$WEBJET_RELAY_CAPACITY_MBPS"
            [ -z "${WEBJET_RATE_CEILING_MBPS:-}" ] || printf 'rate_ceiling_mbps = %d\n' "$WEBJET_RATE_CEILING_MBPS"
        fi
        if [ -n "${WEBJET_PUBLIC:-}" ]; then
            echo
            old_ifs=$IFS; IFS=,
            for e in $WEBJET_PUBLIC; do IFS=$old_ifs; [ -z "$e" ] || public_entry "$e"; IFS=,; done
            IFS=$old_ifs
        fi
        if [ -n "${WEBJET_GATEWAY_ROUTES:-}" ]; then
            echo
            old_ifs=$IFS; IFS=,
            for e in $WEBJET_GATEWAY_ROUTES; do IFS=$old_ifs; [ -z "$e" ] || gateway_entry "$e"; IFS=,; done
            IFS=$old_ifs
        fi
    } > "$CONF.tmp"
    mv "$CONF.tmp" "$CONF"
}

prepare_config() {
    mkdir -p "$(dirname "$CONF")" "$(dirname "$SOCK")" || die "cannot create $(dirname "$CONF") (with --read-only, add --tmpfs /run)"
    if [ -f "$MOUNTED" ] && [ "$CONF" != "$MOUNTED" ]; then
        ln -sf "$MOUNTED" "$CONF"
    elif [ -L "$CONF" ] || { [ -f "$CONF" ] && [ "$(head -n 1 "$CONF")" = "$MARK" ]; } || [ ! -e "$CONF" ]; then
        rm -f "$CONF"
        generate_config
    fi
    # Otherwise WEBJET_CONFIG points at a file the operator provided.
}

checks() {
    if awk '/^\[tun\]/{t=1;next} /^\[/{t=0} t && /^enabled = true/{f=1} END{exit !f}' "$CONF"; then
        [ -c /dev/net/tun ] || die "/dev/net/tun is missing: run with --device /dev/net/tun --cap-add NET_ADMIN (or WEBJET_TUN=false)"
    fi
    if grep -q '^\[\[gateway.route\]\]' "$CONF" && [ "$(cat /proc/sys/net/ipv4/ip_forward 2>/dev/null)" != 1 ]; then
        log "warning: IP forwarding is off; a gateway needs --sysctl net.ipv4.ip_forward=1"
    fi
}

enrollment_string() {
    if [ -n "${WEBJET_ENROLL_FILE:-}" ]; then
        [ -r "$WEBJET_ENROLL_FILE" ] || die "WEBJET_ENROLL_FILE $WEBJET_ENROLL_FILE is not readable"
        tr -d ' \r\n' < "$WEBJET_ENROLL_FILE"
    else
        printf '%s' "${WEBJET_ENROLL:-}"
    fi
}

first_run() {
    [ ! -f "$DATA/node.json" ] || return 0
    mkdir -p "$DATA"
    if [ -n "${WEBJET_GENESIS:-}" ]; then
        [ -r "$WEBJET_GENESIS" ] || die "WEBJET_GENESIS $WEBJET_GENESIS is not readable"
        log "initializing the first controller of a new network from $WEBJET_GENESIS"
        webjetctl init --genesis "$WEBJET_GENESIS"
        return 0
    fi
    ticket=$(enrollment_string)
    [ -n "$ticket" ] || die "this node is not enrolled: set WEBJET_ENROLL (or WEBJET_ENROLL_FILE) to its enrollment string, or WEBJET_GENESIS for the first controller of a new network"
    log "enrolling this node"
    webjetctl enroll "$ticket"
}

case "${1:-}" in
    webjetd)
        case "${2:-}" in
            run)
                prepare_config
                checks
                first_run
                role agent
                ;;
            signer) role signer ;;
            *)
                prepare_config
                role other
                ;;
        esac
        ;;
    *) role other ;;
esac
exec "$@"
